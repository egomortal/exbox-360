def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if checked-in output is stale")
    args = parser.parse_args()
    rows = parse(SPEC.read_text(encoding="utf-8"))
    for name, content in generate(rows).items():
        path = OUTPUT / name
        data = content.encode("utf-8")
        if args.check:
            if not path.exists() or path.read_bytes() != data:
                raise SystemExit(f"Stale generated output: {path}")
        else:
            path.write_bytes(data)
    print(f"Validated {len(rows)} production bindings" + (" (outputs current)" if args.check else " (generated)"))


if __name__ == "__main__":
    main()
