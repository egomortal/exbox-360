"""Generate the user-stub X-macro table from the reviewed behavior spec."""
from pathlib import Path
import re
import sys
root = Path(__file__).resolve().parents[1]
spec = (root / "docs/astra/EDITOR-LAYER-SPEC.md").read_text()
block = spec.split("<!-- BEGIN USER STUB TABLE -->", 1)[1].split("<!-- END USER STUB TABLE -->", 1)[0]
rows = re.findall(r"^\| (__imp__\w+) \| (preserve|0x[0-9a-fA-F]+|[0-9]+) \| (none) \|$", block, re.M)
assert len(rows) == 56 and len({r[0] for r in rows}) == 56
lines = ["// Generated by tools/generate_editor_user_stubs.py; edit the spec table."]
for name, value, _ in rows:
    mode = "preserve" if value == "preserve" else "set"
    number = "0" if mode == "preserve" else str(int(value, 0))
    lines.append(f"EDITOR_USER_STUB({name}, {mode}, {number})")
output = "\n".join(lines) + "\n"
dest = root / "modules/editor_layer/user_stubs.inc"
if "--check" in sys.argv:
    assert dest.read_text() == output, "stub table is stale"
else:
    dest.write_text(output)
print(f"Verified {len(rows)} spec-derived stub contracts")
