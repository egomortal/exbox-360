"""Export original local transport metrics without inventing missing widths.
Every source archive/member hash is recorded. A zero width remains unresolved;
the renderer retains its explicitly documented host fallback for that cell.
"""
from pathlib import Path
import sys,json,hashlib,argparse
from input_paths import dashboard_resources
R=Path(__file__).resolve().parents[1];sys.path.insert(0,str(R/'tools/xur5'))
from custom_scenes import reader,walk
from theme_states import members
CASES={1888:'Blades/Retail/1888',6770:'Blades/Retail/6770',9199:'NXE/Retail/9199',13604:'Kinect/Retail/13604',15574:'Metro/V1/Retail/15574',17559:'Metro/V2/Retail/17559'}
IDS={'video':['btn_Play','btn_Last','btn_RR','btn_Stop','btn_FF','btn_Next'],'picture':['btn_Play','btn_PrevTrack','btn_Stop','btn_NextTrack','btn_Shuffle','btn_Loop','btn_RotateRight','btn_RotateLeft']}
def collect(resources, archives=None):
 S=Path(resources)
 records=[];layouts=[]
 for build,directory in CASES.items():
  row={'build':build}
  for kind,package,scene in [('video','dvd','XmfPadPlayback.xur'),('picture','pictures','slideshowControls.xur')]:
   path=S/directory/'dash.xex'/package;archive=archives.read(path) if archives else path.read_bytes();packed=archives.lookup(path) if archives else dict(members(archive));data=packed.get(scene)
   if data is None:row[kind]=None;records.append(dict(build=build,kind=kind,status='absent',source=str(path),archive_sha256=hashlib.sha256(archive).hexdigest()));continue
   if archives and hasattr(archives,'note'):archives.note(path,scene,'transport-layout-and-timing')
   tree=reader(data,build=build).decode();nodes={n.get('props',{}).get('Id'):n.get('props',{}) for n in walk(tree)};cells=[]
   for identity in IDS[kind]:
    p=nodes[identity];pos=p.get('Position',[0,0,0]);scale=p.get('Scale',[1,1,1]);pivot=p.get('Pivot',[0,0,0]);rotation=p.get('Rotation',[0,0,0,1])
    transform_verified=all(abs(v)<1e-6 for v in pivot) and all(abs(v)<1e-6 for v in rotation[:3])
    if not transform_verified:print('Unimplemented authored transform retained',build,kind,identity,pivot,rotation)
    cells.append(dict(id=identity,x=pos[0],y=pos[1],width=p.get('Width',0),height=p.get('Height',0),scale_x=scale[0],scale_y=scale[1],width_verified='Width' in p,transform_verified=transform_verified,rotation=rotation,pivot=pivot))
   row[kind]=cells;records.append(dict(build=build,kind=kind,status='decoded',source=str(path),archive_sha256=hashlib.sha256(archive).hexdigest(),member=scene,member_sha256=hashlib.sha256(data).hexdigest(),canvas=tree.get('props'),cells=cells))
  layouts.append(row)
 return layouts,records

_HEADER='''#pragma once
// Generated by tools/build_media_transport_metrics.py from original scenes.
// Source hashes and unresolved cells: private/q10/transport-metrics.json.
// These are LOCAL metrics. Host viewport placement and skin composition are
// separate; omitted source widths must not silently acquire another era's size.
namespace media_transport {
struct Cell { double x,y,width,height,scale_x,scale_y; bool transform_verified; };
struct Layout { int build; bool video_available; Cell video[6],picture[8]; };
struct Pixels { int x,y,w,h; };
'''
_FOOTER='''};
inline const Cell* cell_for(int build,int index,bool video) {
 if(index<0 || index>=(video?6:8))return nullptr;
 for(const auto& row:kLayouts)if(row.build==build)
  return video?(row.video_available?&row.video[index]:nullptr):&row.picture[index];
 return nullptr; // A different update needs its own verified extraction.
}
inline Pixels project(const Cell& cell,double sx,double sy,double fallback_width,double fallback_height) {
 const double width=cell.width>0?cell.width*cell.scale_x:fallback_width;
 const double height=cell.height>0?cell.height*cell.scale_y:fallback_height;
 // Convert absolute edges once, preserving authored subpixel spacing.
 const int x=int(cell.x*sx),y=int(cell.y*sy);
 return {x,y,int((cell.x+width)*sx)-x,int((cell.y+height)*sy)-y};
}
} // namespace media_transport
'''

def cell(c):return '{'+','.join(format(c[k],'.9g') for k in ['x','y','width','height','scale_x','scale_y'])+','+('true' if c['transform_verified'] else 'false')+'}'


def render(layouts):
 head=_HEADER+'inline constexpr Layout kLayouts[]={\n'
 for row in layouts:
  video=','.join(cell(c) for c in row['video']) if row['video'] else '{}'
  picture=','.join(cell(c) for c in row['picture'])
  head+=' {'+str(row['build'])+','+('true' if row['video'] else 'false')+',{'+video+'},{'+picture+'}},\n'
 return (head+_FOOTER).encode('utf-8')


def export(resources, output, archives=None):
 layouts,records=collect(resources,archives)
 output=Path(output);(output/'private/q10').mkdir(parents=True,exist_ok=True)
 (output/'media_transport_layout.hpp').write_bytes(render(layouts))
 (output/'private/q10/transport-metrics.json').write_bytes((json.dumps(records,indent=2)+'\n').encode('utf-8'))
 print('Exported',len(layouts),'builds; unresolved source widths',sum(not c['width_verified'] for a in records for c in a.get('cells',[])))
 return layouts,records


def main():
 parser=argparse.ArgumentParser(description=__doc__)
 parser.add_argument('--resources',type=Path,default=dashboard_resources(R),help='Decrypted dashboard resource tree (default: inputs/dashboard-resources)')
 parser.add_argument('--output',type=Path,default=R,help='Output project/scratch root; original inputs are read-only')
 args=parser.parse_args()
 if not args.resources.is_dir():parser.error('Dashboard resources not found: '+str(args.resources))
 export(args.resources,args.output)


if __name__=='__main__':main()
